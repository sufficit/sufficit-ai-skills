#!/usr/bin/env python3
"""Generates catalog/SKILLS.md: one link per skill package, from the import manifest.

The index is the documentation parent of every SKILL.md (README.md links it).
Usage:
  python3 scripts/build_skill_index.py          # rewrite catalog/SKILLS.md
  python3 scripts/build_skill_index.py --check  # exit 1 when it is stale
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / "catalog/SKILLS.md"


def description(skill_md: Path) -> str:
    """Front-matter description: plain, quoted, folded (>) or literal (|), possibly multi-line."""
    front = skill_md.read_text(encoding="utf-8").split("---\n", 2)[1].splitlines()
    for index, line in enumerate(front):
        if not line.startswith("description:"):
            continue
        parts = [line.split(":", 1)[1].strip()]
        if re.fullmatch(r"[>|][+-]?", parts[0]):
            parts = []
        for following in front[index + 1:]:
            if following and not following[0].isspace():
                break
            parts.append(following.strip())
        text = re.sub(r"\s+", " ", " ".join(parts)).strip()
        if len(text) > 1 and text[0] == text[-1] and text[0] in "\"'":
            text = text[1:-1]
        return text if len(text) <= 160 else text[:157].rstrip() + "..."
    return ""


def markdown_text(text: str) -> str:
    """Inert table-cell text: a truncated code span or tag must not swallow later rows."""
    text = text.replace("`", "")
    for char, escaped in (("\\", "\\\\"), ("|", "\\|"), ("<", "&lt;"), ("[", "\\["), ("]", "\\]"), ("*", "\\*"), ("_", "\\_")):
        text = text.replace(char, escaped)
    return text


def render(root: Path = ROOT) -> str:
    manifest = json.loads((root / "catalog/import-manifest.json").read_text(encoding="utf-8"))
    authors = {source["id"]: source["author"] for source in manifest["sources"]}
    lines = [
        "# Skill index",
        "",
        "Generated by `scripts/build_skill_index.py` from",
        "[`import-manifest.json`](import-manifest.json); do not edit by hand.",
        "Every skill package is reachable from here, which keeps each `SKILL.md`",
        "inside the repository's documentation hierarchy.",
        "",
    ]
    by_collection: dict[str, list[dict]] = {}
    for skill in manifest["skills"]:
        by_collection.setdefault(skill["path"].split("/")[1], []).append(skill)
    for collection in sorted(by_collection):
        lines += [f"## {collection}", "", "| Skill | Card | Source | Description |", "| --- | --- | --- | --- |"]
        for skill in sorted(by_collection[collection], key=lambda item: item["path"]):
            summary = markdown_text(description(root / skill["path"] / "SKILL.md"))
            card = f"[card](../{skill['path']}/skill-card.md)" if (root / skill["path"] / "skill-card.md").is_file() else ""
            lines.append(f"| [{skill['name']}](../{skill['path']}/SKILL.md) | {card} | "
                         f"{authors.get(skill['sourceId'], skill['sourceId'])} | {summary} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = render()
    if "--check" in sys.argv[1:]:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != content:
            print("catalog/SKILLS.md is stale; run: python3 scripts/build_skill_index.py", file=sys.stderr)
            return 1
        print("catalog/SKILLS.md is up to date.")
        return 0
    INDEX.write_text(content, encoding="utf-8")
    print(f"Wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
